const LATE = /翡冷翠|神曲|卢塞恩|嘉宝|梦露|贞德|茵格里切宝|小空|小净|介丘|胡须迎客|被遗忘国度|遗忘历|太子|左岸天王|恐惧魔王|巫妖王|教宗|权杖祭祀|圣奇奥|果果|壹条|穆里尼奥|时空大裂缝|花廷|花王|花相/;

for (const [f, keep] of Object.entries(ANCIENT_NODES)) {
  const lines = fs.readFileSync(path.join(R, f + '.yaml'), 'utf8').split('\n');
  const heads = [];
  lines.forEach((l, i) => { if (/^[^\s#][^:]*:\s*$/.test(l)) heads.push({ i, k: l.replace(/:.*$/, '') }); });
  const out = [];
  for (let h = 0; h < heads.length; h++) {
    if (!keep.includes(heads[h].k)) continue;
    const s = heads[h].i, e = h + 1 < heads.length ? heads[h + 1].i : lines.length;
    for (let j = s + 1; j < e; j++) {
      if (LATE.test(lines[j])) out.push({ l: j + 1, node: heads[h].k, t: lines[j].trim() });
    }
  }
  if (!out.length) continue;
  console.log(`\n══ ${f} ══`);
  for (const o of out) console.log(`  L${String(o.l).padStart(4)} [${o.node}] ${o.t.slice(0, 140)}`);
}
