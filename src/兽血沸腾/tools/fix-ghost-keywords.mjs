// 修正人名类条目 keyword 的两类缺陷。
//
// 缺陷来源（根因在 make-npc-patch.mjs L43-49）：
//   它把 NPC yaml 里的 `姓名:` 整行当作关键词来源，
//     `姓名: 奥尼尔，全名沙奎尔·奥尼尔，绰号奥胖`
//   于是「奥尼尔，全名沙奎尔」「贝肯鲍尔，全名贝肯鲍尔」这种**半句描述**
//   被原样塞进 keywords。这类词在原文里 0 命中，永远匹配不到任何楼层。
//   同一行还衍生出「大卫」「路易斯」这种取点号前缀得到的超短词、
//   `宝莱坞公证殿下`（把 `宝莱坞大陆的梦露公证殿下` 从中间切断）、
//   `普斯卡什.巴拉克`（原文只有 `普斯卡什` / `普斯卡什大师`，全篇无 `巴拉克`）。
//
// 判据（术语纪律「关键词 / 别名必须是原文真有的字串」）：
//   每个关键词必须是原文真实出现的字串。这里逐条用原文核验后才改。
import fs from 'fs';

const ST = 'src/兽血沸腾/tavern-cards-state.json';
const 原 = fs.readFileSync('src/兽血沸腾/兽血沸腾.txt', 'utf8');
const 数 = s => 原.split(s).length - 1;

// [类型, 条目名, 删, 加]
const 修 = [
  ['角色', '普斯卡什_基础信息', ['普斯卡什.巴拉克'], ['普斯卡什大师']],
  ['角色', '普斯卡什_性格调色盘', ['普斯卡什.巴拉克'], ['普斯卡什大师']],

  ['角色', '梦露_基础信息', ['宝莱坞公证殿下'], ['玛丽莲', '梦露陛下', '梦露女王']],
  ['角色', '梦露_性格调色盘', ['宝莱坞公证殿下'], ['玛丽莲', '梦露陛下', '梦露女王']],
  ['角色', '梦露_私密档案', ['宝莱坞公证殿下'], ['玛丽莲', '梦露陛下', '梦露女王']],
  ['角色', '梦露_私密阶段', ['宝莱坞公证殿下'], ['玛丽莲', '梦露陛下', '梦露女王']],

  ['NPC', '依莎贝拉', ['依莎贝拉.列娜'], []],
  ['NPC', '保罗.马尔蒂尼', ['保罗.马尔蒂尼，'], ['保罗·马尔蒂尼']],
  ['NPC', '卡佩罗', ['卡佩罗.夏尔巴', '卡佩罗，'], []],
  ['NPC', '卡萨诺', ['卡萨诺.夏尔巴', '卡萨诺，'], []],
  ['NPC', '古德', ['古德，又写作潘帅'], []],
  ['NPC', '四殿下', ['四殿下，通称玄奥的壮汉殿下'], []],
  ['NPC', '奥尼尔', ['奥尼尔，全名沙奎尔'], ['沙奎尔', '奥胖']],
  ['NPC', '寇涛', ['寇涛人鱼王'], ['寇涛人鱼']],
  ['NPC', '布拉特', ['布拉特红衣大祭司'], ['红衣大祭司布拉特']],
  ['NPC', '菲高', ['菲高，全名路易斯'], ['路易斯.菲利浦.菲高']],
  ['NPC', '贝克汉姆', ['贝克汉姆，全名大卫'], ['大卫·贝克汉姆', '小贝', '万人迷']],
  ['NPC', '贝肯鲍尔', ['贝肯鲍尔，全名贝肯鲍尔'], ['波赛东']],
];

const st = JSON.parse(fs.readFileSync(ST, 'utf8'));
const 报告 = [];
let 改条 = 0;

for (const [类型, 名, 删, 加] of 修) {
  const leaf = st.entryManifest[类型]?.[名];
  if (!leaf) { 报告.push(`✗ 【${类型}】${名} 条目不存在`); continue; }

  const 前 = new Set(leaf.keywords ?? []);
  const 真删 = 删.filter(k => 前.has(k));
  for (const k of 真删) 前.delete(k);
  for (const k of 加) 前.add(k);
  const 后 = [...前];

  // 逐词核验：原文 0 命中的一律不许留下
  const 坏 = 后.filter(k => 数(k) === 0);
  if (坏.length) { 报告.push(`✗ 【${类型}】${名} 修完仍有 0 命中：${坏.join('、')}`); continue; }

  leaf.keywords = 后;
  if (leaf.strategy?.keys) leaf.strategy.keys = [...后];
  改条++;
  报告.push(`✓ 【${类型}】${名}\n     删 ${真删.length}：${真删.join('、') || '（无）'}\n     加 ${加.length}：${加.join('、') || '（无）'}\n     得：${后.join(' / ')}`);
}

fs.writeFileSync(ST, JSON.stringify(st, null, 2) + '\n', 'utf8');
console.log(报告.join('\n'));
console.log(`\n══ 改了 ${改条} 个条目，state 已写回 ══`);
