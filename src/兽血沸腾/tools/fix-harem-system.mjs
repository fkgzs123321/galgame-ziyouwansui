// 后宫与孕事系统.yaml 三处修补：① 珊瑚美人 → 谭雅（术语纪律 L109 已裁定）② L19 与 NSFW 全开冲突 ③ 补 房事 字段说明
import fs from 'fs';
const p = 'src/兽血沸腾/世界书/世界观/后宫与孕事系统.yaml';
let t = fs.readFileSync(p, 'utf8');
const before = t;

// ① 退役名 → 正式名
t = t.replace(/珊瑚美人/g, '谭雅');

// ② 亲密记录不再要求淡化露骨细节（NSFW 全开），改为写清部位与过程，仍保留可检索性
t = t.replace(
  /^  - 摘要只写发生了什么与关键对话，不写露骨细节，留给后续剧情引用$/m,
  '  - 摘要写清对象、部位、过程与关键对话，用原作那套直白的说法落到具体动作与反应上；' +
  '不写概括性的评价词，也不把过程压缩成一句发生了什么'
);

// ③ 补 房事 字段：与 schema.ts 的 房事 对象、HaremPanel.vue 的渲染契约一致
if (!/^房事台账:/m.test(t)) {
  t = t.replace(/\n*$/, `
房事台账:
  - 每次侍寝按对象写入关系项下的房事，含侍寝次数、最近一次、身体开发、名器觉醒、部位、性癖、床评七项
  - 身体开发按部位逐项累加，已解锁的部位不因时间流逝回退，只随新的经历继续推进
  - 名器觉醒一经确认便长期有效，同一对象的名器不会重复觉醒或改名
  - 床评随身体开发与性癖解锁同步上调，不因单次表现好坏下调
  - 部位项按固定的部位名逐项记录，名称用原作的说法，不用笼统的代称
  - 性癖以条目形式累加，重复触发同一性癖只增加次数，不新增条目
  - 怀有身孕的对象在临产前后暂停房事计数，分娩后再恢复
`);
}

fs.writeFileSync(p, t, 'utf8');
console.log(`写入 ${p}`);
console.log('珊瑚美人 残留:', (t.match(/珊瑚美人/g) || []).length);
console.log('谭雅 出现:', (t.match(/谭雅/g) || []).length);
console.log('房事台账 已加:', /^房事台账:/m.test(t));
