// 探针：逐个裸前缀的归属裁决。
//
// 判据：裸前缀安全 ⇔ 它出现的行里绝大多数指向本条目的那个人。
// 测法：该前缀出现的行中，含「能唯一指向目标的其他词」的占比。
import fs from 'fs';

const 行 = fs.readFileSync('src/兽血沸腾/兽血沸腾.txt', 'utf8').split('\n');
const 含 = s => 行.filter(l => l.includes(s));

// [裸前缀, 所属条目, 指向目标的判别词[], 指向别人的判别词[]]
const 案 = [
  ['保罗', '保罗.马尔蒂尼', ['马尔蒂尼', '保罗·马尔蒂尼', '保罗.马尔蒂尼'], ['纽曼', '保罗二世', '圣保罗']],
  ['乔治', '乔治.贝斯特', ['贝斯特', '曼联'], ['十字旗', '十字']],
  ['克里斯蒂安', '维埃里', ['维埃里'], ['贝尔', '六翼天王', '撕裂的末日']],
  ['阿里', '阿里.代伊', ['代伊', '龙城'], ['阿里娜', '阿里巴巴']],
  ['米娅', '米娅', ['米娅·哈姆', '哈姆', '女足'], []],
  ['青雅', '白素青', ['白玉', '白素青'], []],
  ['克拉克', '克拉克·盖博', ['盖博'], []],
  ['加图索', '加图索·丹泽', ['丹泽'], []],
  ['托蒂', '托蒂·夏尔巴', ['夏尔巴', '伯爵'], []],
  ['托马西', '托马西·丹泽', ['丹泽', '圣骑士'], []],
  ['幽月儿', '幽月儿', ['主母', '杜垩登', '萝丝'], []],
  ['海伦', '海伦.列娜', ['列娜', '茉儿', '刘震撼'], []],
  ['福格森', '福格森.徐', ['.徐'], []],
];

console.log('══ 裸前缀归属裁决 ══\n');
for (const [裸, 属, 目标词, 他人词] of 案) {
  const 全 = 含(裸);
  const 向目标 = 全.filter(l => 目标词.some(t => l.includes(t))).length;
  const 向他人 = 全.filter(l => 他人词.length && 他人词.some(t => l.includes(t))).length;
  const 无据 = 全.length - 向目标 - 向他人;
  const 占 = 全.length ? (向目标 / 全.length * 100).toFixed(0) : '0';
  const 决 = 向目标 / Math.max(1, 全.length) >= 0.6 ? '✅ 安全' : '❌ 污染';
  console.log(`【${裸}】→ ${属}   共 ${全.length} 行`);
  console.log(`     指向目标 ${向目标} (${占}%)   指向他人 ${向他人}   本行无判别词 ${无据}   → ${决}`);
  if (他人词.length && 向他人 > 0) {
    const 样 = 全.filter(l => 他人词.some(t => l.includes(t)))[0];
    console.log(`     他人样本： ${样.trim().slice(0, 88)}`);
  }
  console.log('');
}
