// 只改「语言特征:」之前的段（与 audit-npc-forward-leak.mjs 的检查段一致）。
// 保留 永贝里（同名撞车误报）与 罗森博格（跨度仅 1 章）。
import fs from 'fs';
import path from 'path';

const NPC = 'src/兽血沸腾/世界书/NPC';

const 改 = {
  '罗德曼.yaml': [
    ['、公认的刀圣', ''],
    ['    - 扛着白旗当敌使走向两位山丘之王，逼两位矮人王给他让出一条道',
     '    - 扛着白旗当敌使走向敌阵，硬生生从堵路的巨汉中间穿了过去'],
  ],
  '古德.yaml': [
    ['把亲生兄弟古川引荐给老板，替族人争取在翡冷翠定居',
     '把亲生兄弟古川引荐给老板，替族人争取一处安身的地方'],
    ['老板点名要他的族人到翡冷翠定居，他当面回一句我是你的追随者',
     '老板点名要他的族人一起走，他当面回一句我是你的追随者'],
  ],
  '齐丹大萨满.yaml': [
    ['赠威瑟斯庞神庙的一头雷兽给翡冷翠骑兵',
     '把威瑟斯庞神庙的一头雷兽赠给刘震撼麾下的骑兵'],
  ],
  '迦莎.yaml': [
    ['在十星连珠寒潭边替翡冷翠一方配合嫁接艾莉婕的计划，此后随族编入夏宫太保团',
     '在十星连珠寒潭边替翡冷翠一方配合嫁接艾莉婕的计划'],
  ],
  '道根.yaml': [
    ['一万年前留下的火铳与图纸成了翡冷翠的看家本事，刘震撼手里的古力火铳便是照着他的法子在用',
     '一万年前留下的火铳与图纸，刘震撼手里的古力火铳便是照着他的法子在用'],
  ],
  '贝拉米.yaml': [
    ['在内陆城里跟人类讲价钱、抖身份，替翡冷翠撑场面',
     '在内陆城里跟人类讲价钱、抖身份，替刘震撼撑场面'],
  ],
  '赞迪.yaml': [
    ['加里曼丹城被屠后在外围被翡冷翠航空兵捉住',
     '加里曼丹城被屠后在外围被刘震撼的人捉住'],
  ],
};

let 总 = 0; const 失败 = [];
for (const [f, 对] of Object.entries(改)) {
  const p = path.join(NPC, f);
  const t = fs.readFileSync(p, 'utf8');
  const 头 = t.split(/\n(?=语言特征:)/)[0];   // 只允许在这段里替换
  let 段 = 头, n = 0;
  for (const [a, b] of 对) {
    if (!段.includes(a)) { 失败.push(`${f}: 未找到「${a.slice(0, 30)}」`); continue; }
    const c = 段.split(a).length - 1;
    段 = 段.split(a).join(b); n += c;
  }
  if (段 !== 头) { fs.writeFileSync(p, 段 + t.slice(头.length), 'utf8'); 总 += n; }
  console.log(`${段 !== 头 ? '✓' : ' '} ${f.padEnd(20)} 改 ${n} 处`);
}
console.log(`\n共改 ${总} 处`);
if (失败.length) { console.log('\n未命中：'); 失败.forEach(x => console.log('  ' + x)); }
