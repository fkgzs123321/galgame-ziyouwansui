// 角色速览 陈旧条目清理 + 四殿下 说话风格 残句修正
// 依据：潘帅 ≡ 古德（L9426「潘帅，你看呢？」…正在扮酷的古德 / L9642「熊猫们都在看着『潘帅』古德」）；
//       普斯卡什大师 → 普斯卡什（既有角色专条）；唐藏亲王（冬五）拆错位，
//       冬五本人封号唐藏亲王（冬五.yaml L2），四殿下另有专条。
import fs from 'fs';
const CAT = 'src/兽血沸腾/世界书/角色/角色速览.yaml';
let t = fs.readFileSync(CAT, 'utf8');
const before = t;

// ① 潘帅 与 古德 是同一人 → 删掉重复的潘帅块，把别名并进古德备注
t = t.replace(
  /  - 姓名: 古德\n    性别: 男\n    身份: 熊猫武士首领，主角贴身护卫\n/,
  '  - 姓名: 古德\n    性别: 男\n    身份: 熊猫武士首领，主角贴身护卫\n    备注: 又称潘帅，潘塔族熊猫武士\n'
);
t = t.replace(/  - 姓名: 潘帅\n    性别: 男\n    身份: 潘塔族熊猫武士首领\n/, '');

// ② 普斯卡什大师 → 普斯卡什（与既有角色专条同名）
t = t.replace(/  - 姓名: 普斯卡什大师\n/, '  - 姓名: 普斯卡什\n');

// ③ 唐藏亲王（冬五）→ 冬五：封号与名号要分清，冬五是五殿下
t = t.replace(
  /  - 姓名: 唐藏亲王（冬五）\n    性别: 男\n    身份: 唐藏帝国五殿下，禁卫统帅\n/,
  '  - 姓名: 冬五\n    性别: 男\n    身份: 唐藏帝国第五亲王，执金吾领卫，丝绸大陆第一大力士\n    备注: 封号唐藏亲王，四殿下与皇帝称他小五\n'
);

// ④ 小空的师父是四殿下（玄奥的壮汉殿下），不是笼统的「唐藏亲王」
t = t.replace(
  /  - 姓名: 小空\n    性别: 男\n    身份: 大力巨猿修炼出人形，唐藏亲王大学徒\n/,
  '  - 姓名: 小空\n    性别: 男\n    身份: 大力巨猿修炼出人形，四殿下的大徒弟\n'
);

// ⑤ 阵营速查 唐藏帝国 一行拆对
t = t.replace(/^   唐藏帝国: 唐藏亲王冬五、小空、小净$/m, '   唐藏帝国: 冬五、四殿下、小空、小净');
// 圣保罗教廷一行的 普斯卡什 保留（正确）
fs.writeFileSync(CAT, t, 'utf8');
console.log(`角色速览 ${before.length} → ${t.length} B`);
console.log('潘帅 残留:', (t.match(/潘帅/g) || []).length, '（应 1，在古德备注里）');
console.log('普斯卡什大师 残留:', (t.match(/普斯卡什大师/g) || []).length);
console.log('唐藏亲王（冬五） 残留:', (t.match(/唐藏亲王（冬五）/g) || []).length);

// ⑥ 四殿下 说话风格 以逗号开头（split 时首分句为空）
const F4 = 'src/兽血沸腾/世界书/NPC/四殿下.yaml';
let f4 = fs.readFileSync(F4, 'utf8');
const b4 = f4;
f4 = f4.replace(/^  说话风格: ，/, '  说话风格: ');
fs.writeFileSync(F4, f4, 'utf8');
console.log(`\n四殿下 说话风格 修正: ${b4 !== f4}`);
console.log('  ' + (f4.match(/^  说话风格:.*$/m) || [''])[0].slice(0, 90));
